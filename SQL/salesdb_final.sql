#Inner Join for Order Details 
-- Join orders, order_items, and products to display detailed line items. 
select * from salesdb.orders as o
inner join salesdb.order_items as oi
on o.order_id = oi.order_id
inner join salesdb.products as p
on p.product_id = oi.product_id;

#Total Sales by Store 
-- Write a query to group sales (total_price) by each store_id. 
select o.store_id,sum(oi.total_price) as total_sales from salesdb.orders as o
inner join salesdb.order_items as oi
on o.order_id = oi.order_id
group by o.store_id;

